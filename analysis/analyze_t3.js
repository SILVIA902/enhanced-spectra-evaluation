'use strict';

const fs = require('fs');
const path = require('path');

const CONFIG = process.argv[2] || 'main';
const BASE = path.join(__dirname, '..', 'results', 'T3', CONFIG);
const OUT = path.join(BASE, 'analysis');
if (!fs.existsSync(path.join(BASE, 'targets.csv'))) { console.error(`targets.csv not found in ${BASE}`); process.exit(1); }
fs.mkdirSync(OUT, { recursive: true });

function readCsv(file) {
  const lines = fs.readFileSync(file, 'utf8').trim().split('\n');
  const head = lines[0].split(',');
  return lines.slice(1).filter(Boolean).map(l => {
    const v = l.split(','); const o = {};
    head.forEach((k, i) => { o[k] = v[i]; });
    return o;
  });
}
const mean = a => (a.length ? a.reduce((s, v) => s + v, 0) / a.length : NaN);
function pctl(a, p) {
  const s = [...a].sort((x, y) => x - y); const i = (s.length - 1) * p;
  const lo = Math.floor(i), hi = Math.ceil(i); return s[lo] + (s[hi] - s[lo]) * (i - lo);
}
const fmt = (v, d = 1) => (Number.isNaN(v) ? '--' : v.toFixed(d));
const int = v => Number(v);

const targets = readCsv(path.join(BASE, 'targets.csv'));
const attempts = readCsv(path.join(BASE, 'attempts.csv'));
const summary = JSON.parse(fs.readFileSync(path.join(BASE, 'summary.json'), 'utf8'));

const SUBS = [
  ['a', 'Same UID, $k$ concurrent \\texttt{ConsumeByUID}', 'Single consumption (Eq.~16)'],
  ['b1', 'Same UID, $k$ different packages', 'Active UID-binding uniqueness (Eq.~13)'],
  ['b2', '$k$ different UIDs, same package', 'Active output-lot binding uniqueness (Eq.~14)'],
  ['c', 'Same input lot, $k$ transformations', 'Input-consumption integrity'],
];
const rows = [];
for (const [sub, scenario, invariant] of SUBS) {
  const ks = [...new Set(targets.filter(t => t.subtest === sub).map(t => int(t.k)))].sort((a, b) => a - b);
  for (const k of ks) {
    const T = targets.filter(t => t.subtest === sub && int(t.k) === k);
    const A = attempts.filter(a => a.subtest === sub && int(a.k) === k);
    const okLat = A.filter(a => a.outcome === 'COMMITTED' && a.l_e2e_ms !== '').map(a => Number(a.l_e2e_ms));
    rows.push({
      sub, scenario, invariant, k,
      targets: T.length,
      attempts: A.length,
      exactlyOne: T.filter(t => int(t.committed) === 1).length,
      noCommit: T.filter(t => int(t.committed) === 0).length,
      multi: T.filter(t => int(t.committed) > 1).length,
      mvcc: T.reduce((s, t) => s + int(t.mvcc), 0),
      rejected: T.reduce((s, t) => s + int(t.rejected), 0),
      scans: T.reduce((s, t) => s + int(t.repeated_scans), 0),
      other: T.reduce((s, t) => s + int(t.other), 0),
      postOk: T.filter(t => t.postcheck_ok === 'true').length,
      violations: T.filter(t => t.safety_ok !== 'true').length,
      spreadP50: pctl(T.map(t => Number(t.release_spread_ms)), 0.5),
      spreadMax: Math.max(...T.map(t => Number(t.release_spread_ms))),
      completion: mean(T.map(t => Number(t.completion_ms))),
      winnerLat: mean(okLat),
    });
  }
}

fs.writeFileSync(path.join(OUT, 't3_summary.csv'),
  ['subtest,k,targets,attempts,exactly_one,no_commit,multiple_commits,mvcc,rejected,repeated_scans,other,' +
   'postcheck_ok,violations,release_spread_p50_ms,release_spread_max_ms,completion_mean_ms,winner_latency_mean_ms',
   ...rows.map(r => [r.sub, r.k, r.targets, r.attempts, r.exactlyOne, r.noCommit, r.multi, r.mvcc, r.rejected,
     r.scans, r.other, r.postOk, r.violations, fmt(r.spreadP50, 3), fmt(r.spreadMax, 3), fmt(r.completion, 3),
     fmt(r.winnerLat, 3)].join(','))].join('\n') + '\n');

const tot = k => rows.reduce((s, r) => s + r[k], 0);
const totTargets = tot('targets'), totAttempts = tot('attempts'), totViol = tot('violations');
const totMvcc = tot('mvcc'), totRej = tot('rejected'), totScans = tot('scans'), totOther = tot('other');
const totExactly = tot('exactlyOne'), totPost = tot('postOk'), totNoCommit = tot('noCommit');
const maxSpread = Math.max(...rows.map(r => r.spreadMax));
const p = summary.prep || {};
const retryTotal = p.retryReasons ? Object.values(p.retryReasons).reduce((s, v) => s + v, 0) : 0;
const day = (summary.startedAt || '').slice(0, 10);
const hhmm = iso => new Date(iso).toLocaleTimeString('it-IT', { hour: '2-digit', minute: '2-digit', timeZone: 'Europe/Rome' });

const tableRows = [];
for (const [sub, scenario, invariant] of SUBS) {
  const rs = rows.filter(r => r.sub === sub);
  if (!rs.length) continue;
  tableRows.push(`\\multicolumn{9}{l}{\\textbf{T3-${sub}}: ${scenario} -- ${invariant}} \\\\`);
  for (const r of rs) {
    tableRows.push(`\\quad $k=${r.k}$ & ${r.targets} & ${r.attempts} & ${r.exactlyOne} & ${r.mvcc} & ` +
      `${r.rejected + r.scans} & ${r.other} & ${r.postOk}/${r.targets} & ${r.violations} \\\\`);
  }
}

const tex = String.raw`% Generated by analyze_t3.js - paste before \end{document}
\subsection{T3 -- Concurrent conflicting operations}
Executed on ${day} (${hhmm(summary.startedAt)}--${hhmm(summary.finishedAt)} CEST): ${summary.subtests.length}
sub-tests, $k \in \{${summary.ks.join(', ')}\}$ concurrent clients (one gRPC connection each), ${summary.targetsPerK}
targets per $k$ and repetition, $R=${summary.reps}$ repetitions, i.e.\ ${totTargets} targets and ${totAttempts}
conflicting transactions. For each target the $k$ requests were released together (median release spread
${fmt(pctl(rows.map(r => r.spreadP50), 0.5))}\,ms, maximum ${fmt(maxSpread)}\,ms); the expected outcome was
declared before execution in the T3 design above.

\paragraph{Asset preparation.} The ${p.validTx} preparation transactions (productions, transformations,
packages and bindings) were executed by ${p.concurrency} parallel workflows in ${fmt(p.seconds)}\,s
(${fmt(p.validTx / p.seconds)} valid transactions per second). ${retryTotal} endorsements
(${fmt(100 * retryTotal / (p.validTx + retryTotal), 2)}\%) failed with \texttt{ERROR\_INPUT\_NOT\_FOUND} or
\texttt{ERROR\_OUTPUT\_LOT\_NOT\_FOUND} and succeeded when retried: a chained step was endorsed by a peer that
had not yet committed the block containing the previous step, because the client observes the commit status
only on its gateway peer.

\begin{table}[H]
\centering\small
\caption{T3: outcomes of concurrent conflicting operations. \emph{Exactly 1}: targets with exactly one
committed state transition; \emph{MVCC}: requests invalidated at commit with \texttt{MVCC\_READ\_CONFLICT};
\emph{Rejected}: requests rejected by the chaincode at endorsement or committed as repeated scans;
\emph{Other}: infrastructure errors; \emph{Post-check}: targets whose final ledger state matched the expected
state; \emph{Violations}: targets with more than one committed transition or an inconsistent final state.}
\label{tab:t3-outcomes}
\setlength{\tabcolsep}{4pt}
\begin{tabular}{lrrrrrrrr}
\toprule
Configuration & Targets & Requests & Exactly 1 & MVCC & Rejected & Other & Post-check & Violations \\
\midrule
${tableRows.join('\n')}
\midrule
Total & ${totTargets} & ${totAttempts} & ${totExactly} & ${totMvcc} & ${totRej + totScans} & ${totOther} & ${totPost}/${totTargets} & ${totViol} \\
\bottomrule
\end{tabular}
\end{table}

\paragraph{Observations.}
\begin{itemize}
  \item \textbf{No invariant violation.} In all ${totTargets} targets at most one conflicting request produced a
        committed state transition (${totViol} violations); ${totExactly} targets had exactly one
        ${totNoCommit ? `and ${totNoCommit} had none` : 'and none ended without a commit'}. The final ledger
        state matched the expected state in ${totPost} of ${totTargets} targets.
  \item \textbf{Enforcement mechanism.} Because the $k$ requests were released together, they were in most
        cases endorsed before the winning transaction was committed and therefore read the same state version:
        ${totMvcc} of the ${totAttempts - totExactly} losing requests were invalidated by Fabric MVCC validation
        at commit time, while ${totRej + totScans} were endorsed after the winning commit and were rejected by the
        chaincode preconditions (or, for T3-a, recorded as repeated scans). Single consumption, binding uniqueness
        and input-consumption integrity are therefore enforced jointly by the chaincode preconditions (for
        sequential requests) and by MVCC validation (for concurrent requests), as argued in the proof sketches.
  \item \textbf{Scope.} The experiment verifies the digital invariants under concurrent submission by
        authorised clients. It does not test physical tag cloning itself, malicious endorsing peers or
        compromised organisations, which remain outside the evaluated threat classes.
\end{itemize}
`;
fs.writeFileSync(path.join(OUT, 't3_section.tex'), tex);

console.log(`\nT3 ${CONFIG}: ${totTargets} targets, ${totAttempts} conflicting requests`);
console.log('subtest    k   targets  exact.1  MVCC   rejected  other  postcheck  violations  spread-max(ms)  winner latency(ms)');
for (const r of rows) {
  console.log(`${r.sub.padEnd(9)} ${String(r.k).padStart(2)} ${String(r.targets).padStart(9)} ${String(r.exactlyOne).padStart(8)}` +
    ` ${String(r.mvcc).padStart(5)} ${String(r.rejected + r.scans).padStart(10)} ${String(r.other).padStart(6)}` +
    ` ${`${r.postOk}/${r.targets}`.padStart(10)} ${String(r.violations).padStart(11)} ${fmt(r.spreadMax).padStart(15)}` +
    ` ${fmt(r.winnerLat).padStart(21)}`);
}
console.log(`\nTOTAL violations: ${totViol}   postcheck ok: ${totPost}/${totTargets}   infrastructure errors: ${totOther}`);
console.log(`LaTeX block: ${path.join(OUT, 't3_section.tex')}`);
